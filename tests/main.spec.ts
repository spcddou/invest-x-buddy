import {test,expect} from '@playwright/test';
test('plan edit → approvals → real evidence → memo → approved memory → replay',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('button',{name:'生成研究计划'})).toBeEnabled({timeout:30000});
 await page.getByRole('button',{name:'生成研究计划'}).click();
 await expect(page.getByTestId('approval-card')).toContainText('确认研究口径',{timeout:30000});
 await page.getByLabel('步骤 2 目标',{exact:true}).fill('核对证券身份与实时行情');
 await page.getByRole('button',{name:'批准并继续',exact:true}).click();
 await expect(page.getByTestId('approval-card')).toContainText('审阅证据与分歧',{timeout:100000});
 await expect(page.getByTestId('evidence-board')).toBeVisible();
 await page.locator('.evidence-card').first().click();
 await expect(page.getByRole('dialog')).toContainText('实际抓取时间');
 await expect(page.getByRole('dialog')).toContainText('统计口径');
 await page.getByRole('button',{name:'关闭来源'}).click();
 await page.getByRole('button',{name:'批准并继续',exact:true}).click();
 await expect(page.getByTestId('memo')).toContainText('数字核对 通过');
 await page.getByRole('button',{name:'写入长期记忆'}).click();
 await expect(page.getByTestId('approval-card')).toContainText('批准写入长期记忆');
 await page.getByRole('button',{name:'批准并继续',exact:true}).click();
 await expect(page.locator('main [role=alert]')).toContainText('已批准并写入长期记忆');
 await page.getByRole('button',{name:'运行轨迹',exact:true}).click();
 await page.getByRole('button',{name:'确定性回放'}).click();
 await expect(page.locator('.replay-controls')).toContainText('不调用网络');
 await page.getByRole('button',{name:'退出回放'}).click();
 await page.getByLabel('追问',{exact:true}).fill('明天涨停吗？');
 await page.getByRole('button',{name:'追问',exact:true}).click();
 await expect(page.locator('.answer')).toContainText('不提供目标价');
 await page.evaluate(()=>localStorage.clear());
 await page.reload();
 await expect(page.locator('.project')).toHaveCount(1,{timeout:30000});
 await page.locator('nav').getByRole('button',{name:/长期记忆/}).click();
 await expect(page.locator('.note')).toHaveCount(1);
});
test('crash checkpoint resumes without recalling finished steps; failure is explicit',async({page})=>{
 await page.goto('/?simulateCrash=step3&simulateFail=eastmoney');
 await expect(page.getByRole('button',{name:'生成研究计划'})).toBeEnabled({timeout:30000});
 await page.getByRole('button',{name:'生成研究计划'}).click();
 await expect(page.getByTestId('approval-card')).toBeVisible({timeout:30000});
 await page.getByRole('button',{name:'批准并继续',exact:true}).click();
 await expect(page.getByRole('button',{name:'从检查点恢复'})).toBeVisible({timeout:90000});
 const done=await page.locator('.plan-step.done').count();expect(done).toBe(3);
 await page.reload();
 await expect(page.getByRole('button',{name:'从检查点恢复'})).toBeVisible({timeout:30000});
 const stepIds:string[]=[];
 page.on('request',r=>{if(r.url().includes('/api/agent')&&r.method()==='POST'){const b=r.postDataJSON();if(b.action==='step')stepIds.push(b.stepId);}});
 await page.getByRole('button',{name:'从检查点恢复'}).click();
 await expect(page.getByTestId('approval-card')).toContainText('审阅证据与分歧',{timeout:100000});
 expect(stepIds.every(id=>!['step1','step2','step3'].includes(id))).toBe(true);
 await expect(page.locator('.notice.amber').filter({hasText:'降级研究'})).toBeVisible();
});
